function defaultNestedBukkitName(fqcn) {
  const binaryName = fqcn.slice(fqcn.lastIndexOf(".") + 1);
  const parts = binaryName.split("$");
  const outer = parts.shift().replace(/Event$/, "");
  return [outer, ...parts].join("");
}

function bukkitTypes() {
  const bySimpleName = new Map();
  const sourceByClass = new Map();
  for (const sourcePath of walk(apiSource).filter(path => path.endsWith(".java"))) {
    const text = readFileSync(sourcePath, "utf8");
    const declaration = text.match(/public\s+(?:abstract\s+|final\s+)?(?:class|interface|enum|@interface)\s+([A-Za-z_$][\w$]*)/);
    if (!declaration) continue;
    const fqcn = relative(apiSource, sourcePath).replaceAll("\\", "/").replaceAll("/", ".").replace(/\.java$/, "");
    const simpleName = declaration[1];
    sourceByClass.set(fqcn, { text, sourcePath });
    const candidates = bySimpleName.get(simpleName) || [];
    candidates.push(fqcn);
    bySimpleName.set(simpleName, candidates);
  }

  const result = new Map();
  for (const [simpleName, candidates] of bySimpleName) {
    if (candidates.length === 1) {
      result.set(simpleName, candidates[0]);
      continue;
    }
    const selected = canonicalDuplicate.get(simpleName);
    if (!selected || !candidates.includes(selected)) {
      throw new Error(`No canonical Java API type configured for ${simpleName}: ${candidates.join(", ")}`);
    }
    result.set(simpleName, selected);
    for (const candidate of candidates) {
      const packageParts = candidate.slice(0, candidate.lastIndexOf(".")).split(".");
      const qualifier = packageParts.at(-1);
      const alias = `${qualifier[0].toUpperCase()}${qualifier.slice(1)}${simpleName}`;
      if (result.has(alias) && result.get(alias) !== candidate) {
        throw new Error(`Duplicate generated Java API alias ${alias}`);
      }
      result.set(alias, candidate);
    }
  }

  const nestedCandidates = [];
  for (const [fqcn, detail] of [...sourceByClass]) {
    for (const declaration of nestedTypeDeclarations(detail.text, fqcn)) {
      const nestedFqcn = `${fqcn}$${declaration.name}`;
      nestedCandidates.push({ fqcn: nestedFqcn, name: declaration.name, detail });
    }
  }
  for (const candidate of nestedCandidates) {
    const exportedName = nestedBukkitNames.get(candidate.fqcn) || defaultNestedBukkitName(candidate.fqcn);
    if (result.has(exportedName) && result.get(exportedName) !== candidate.fqcn) {
      throw new Error(`Duplicate generated nested Java API name ${exportedName}`);
    }
    result.set(exportedName, candidate.fqcn);
    sourceByClass.set(candidate.fqcn, candidate.detail);
  }
  for (const [exportedName, fqcn] of result) {
    const detail = sourceByClass.get(fqcn);
    if (!detail) continue;
    const parameters = sourceTypeInfo(detail.text, fqcn).typeParameters || [];
    if (parameters.length) declaredGenericBounds.set(exportedName, parameters.map(parameter => parameter.bound));
  }
  return { types: result, sourceByClass };
}

function enumConstants(source, expectedName) {
  const declaration = source.match(new RegExp(`(?:public\\s+)?enum\\s+${expectedName}\\b`));
  if (!declaration) return [];
  const opening = source.indexOf("{", declaration.index + declaration[0].length);
  if (opening < 0) return [];
  const chunks = [];
  let chunk = "";
  let braces = 1;
  let parentheses = 0;
  let brackets = 0;
  let quote = null;
  let escaped = false;
  let lineComment = false;
  let blockComment = false;

  for (let index = opening + 1; index < source.length; index++) {
    const char = source[index];
    const next = source[index + 1];
    if (lineComment) {
      if (char === "\n") lineComment = false;
      continue;
    }
    if (blockComment) {
      if (char === "*" && next === "/") {
        blockComment = false;
        index++;
      }
      continue;
    }
    if (quote) {
      chunk += char;
      if (escaped) escaped = false;
      else if (char === "\\") escaped = true;
      else if (char === quote) quote = null;
      continue;
    }
    if (char === "/" && next === "/") {
      lineComment = true;
      index++;
      continue;
    }
    if (char === "/" && next === "*") {
      blockComment = true;
      index++;
      continue;
    }
    if (char === '"' || char === "'") {
      quote = char;
      chunk += char;
      continue;
    }
    if (char === "{") braces++;
    if (char === "}") {
      braces--;
      if (braces === 0) {
        if (chunk.trim()) chunks.push(chunk);
        break;
      }
    }
    if (char === "(") parentheses++;
    if (char === ")") parentheses--;
    if (char === "[") brackets++;
    if (char === "]") brackets--;

    if (braces === 1 && parentheses === 0 && brackets === 0 && (char === "," || char === ";")) {
      chunks.push(chunk);
      chunk = "";
      if (char === ";") break;
      continue;
    }
    chunk += char;
  }

  return chunks.flatMap(value => {
    const withoutAnnotations = value.replace(/@[A-Za-z_$][\w$]*(?:\s*\([^)]*\))?/g, " ");
    const match = withoutAnnotations.match(/\b([A-Z][A-Z0-9_]*)\b/);
    return match ? [match[1]] : [];
  });
}

function stripJavaComments(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\/\/[^\r\n]*/g, " ");
}

function nestedTypeDeclarations(source, fqcn) {
  const outerName = fqcn.slice(fqcn.lastIndexOf(".") + 1);
  const cleaned = stripJavaComments(source);
  const outer = cleaned.match(new RegExp(
    `public\\s+(?:abstract\\s+|final\\s+|static\\s+)*(class|interface|enum|@interface)\\s+${outerName}\\b[\\s\\S]*?\\{`,
  ));
  if (!outer) return [];
  const implicitPublic = outer[1] === "interface" || outer[1] === "@interface";
  const opening = outer.index + outer[0].length - 1;
  const declarations = [];
  let depth = 1;
  let header = "";
  let quote = null;
  let escaped = false;
  for (let index = opening + 1; index < cleaned.length && depth > 0; index++) {
    const character = cleaned[index];
    if (quote) {
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === quote) quote = null;
      if (depth === 1) header += " ";
      continue;
    }
    if (character === '"' || character === "'") {
      quote = character;
      if (depth === 1) header += " ";
      continue;
    }
    if (character === "{") {
      if (depth === 1) {
        const declaration = stripAnnotations(header).replace(/\s+/g, " ").match(
          /(?:^|[;}])\s*((?:(?:public|protected|private|abstract|final|static|strictfp)\s+)*)(class|interface|enum|@interface)\s+([A-Za-z_$][\w$]*)\b/,
        );
        if (declaration && (implicitPublic || /\bpublic\b/.test(declaration[1]))) {
          declarations.push({ kind: declaration[2], name: declaration[3] });
        }
        header = "";
      }
      depth++;
      continue;
    }
    if (character === "}") {
      depth--;
      if (depth === 1) header = "";
      continue;
    }
    if (depth !== 1) continue;
    header += character;
    if (character === ";") header = "";
  }
  return declarations;
}

function splitTopLevel(value, separator = ",") {
  const result = [];
  let chunk = "";
  let angle = 0;
  let parentheses = 0;
  let brackets = 0;
  for (const character of value) {
    if (character === "<") angle++;
    else if (character === ">") angle = Math.max(0, angle - 1);
    else if (character === "(") parentheses++;
    else if (character === ")") parentheses = Math.max(0, parentheses - 1);
    else if (character === "[") brackets++;
    else if (character === "]") brackets = Math.max(0, brackets - 1);
    if (character === separator && angle === 0 && parentheses === 0 && brackets === 0) {
      result.push(chunk.trim());
      chunk = "";
    } else {
      chunk += character;
    }
  }
  if (chunk.trim()) result.push(chunk.trim());
  return result;
}

function stripAnnotations(value) {
  return value.replace(/@[A-Za-z_$][\w$]*(?:\s*\([^()]*(?:\([^()]*\)[^()]*)*\))?/g, " ");
}

function cleanJavaType(value) {
  return stripAnnotations(value)
    .replace(/\b(?:final|volatile|transient)\b/g, " ")
    .replace(/\?\s+(?:extends|super)\s+/g, "")
    .replace(/^\?$/, "java.lang.Object")
    .replace(/\s+/g, " ")
    .trim();
}

function leadingTypeParameters(value) {
  const cleaned = value.trim();
  if (!cleaned.startsWith("<")) return { parameters: [], rest: cleaned };
  let depth = 0;
  let closing = -1;
  for (let index = 0; index < cleaned.length; index++) {
    if (cleaned[index] === "<") depth++;
    else if (cleaned[index] === ">") {
      depth--;
      if (depth === 0) {
        closing = index;
        break;
      }
    }
  }
  if (closing < 0) return { parameters: [], rest: cleaned };
  const parameters = splitTopLevel(cleaned.slice(1, closing)).flatMap(declaration => {
    const match = declaration.trim().match(/^([A-Za-z_$][\w$]*)(?:\s+extends\s+([\s\S]+))?$/);
    if (!match) return [];
    return [{
      name: match[1],
      bound: (match[2] || "java.lang.Object").split("&")[0].trim(),
    }];
  });
  return { parameters, rest: cleaned.slice(closing + 1).trim() };
}

function parameterList(value, javap = false) {
  if (!value.trim()) return [];
  return splitTopLevel(value).map((raw, index) => {
    const cleaned = cleanJavaType(raw);
    if (javap) {
      const varArgs = cleaned.endsWith("...");
      return { name: `arg${index}`, type: cleaned.replace(/\.\.\.$/, ""), varArgs };
    }
    const compactVarArgs = cleaned.match(/^(.*\S)\.\.\.\s*([A-Za-z_$][\w$]*)$/);
    if (compactVarArgs) {
      return { name: compactVarArgs[2], type: compactVarArgs[1].trim(), varArgs: true };
    }
    const match = cleaned.match(/^(.*\S)\s+([A-Za-z_$][\w$]*)(\[\])?$/);
    if (!match) return { name: `arg${index}`, type: cleaned, varArgs: false };
    const varArgs = match[1].endsWith("...");
    return {
      name: match[2],
      type: `${match[1].replace(/\.\.\.$/, "")}${match[3] || ""}`,
      varArgs,
    };
  });
}

function executableFromHeader(header, simpleName, { implicitPublic = false, javap = false } = {}) {
  let cleaned = stripAnnotations(header)
    .replace(/\s+throws\s+[\s\S]*$/, "")
    .replace(/\s+/g, " ")
    .trim();
  if (!cleaned.includes("(") || /\b(?:class|interface|enum|@interface)\b/.test(cleaned)) return null;
  if (!implicitPublic && !/\bpublic\b/.test(cleaned)) return null;
  if (/\b(?:private|protected)\b/.test(cleaned)) return null;
  const open = cleaned.indexOf("(");
  const close = cleaned.lastIndexOf(")");
  if (close < open) return null;
  const prefix = cleaned.slice(0, open).trim();
  const nameMatch = prefix.match(/([A-Za-z_$][\w$]*)$/);
  if (!nameMatch) return null;
  const name = nameMatch[1];
  const constructor = name === simpleName || (javap && prefix.endsWith(`.${simpleName}`));
  let beforeName = prefix.slice(0, nameMatch.index).trim();
  const staticMember = /\bstatic\b/.test(beforeName);
  beforeName = beforeName
    .replace(/\b(?:public|protected|private|static|final|abstract|default|synchronized|native|strictfp)\b/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const generics = leadingTypeParameters(beforeName);
  beforeName = generics.rest;
  if (!constructor && !beforeName) return null;
  return {
    kind: constructor ? "constructor" : "method",
    name,
    static: staticMember,
    type: constructor ? null : cleanJavaType(beforeName),
    parameters: parameterList(cleaned.slice(open + 1, close), javap),
    typeParameters: generics.parameters,
  };
}

function fieldFromHeader(header, { implicitPublic = false, allowInstance = false } = {}) {
  let cleaned = stripAnnotations(header).replace(/\s+/g, " ").trim();
  if (!cleaned || /\b(?:class|interface|enum|@interface)\b/.test(cleaned)) return null;
  if (!implicitPublic && !/\bpublic\b/.test(cleaned)) return null;
  if (/\b(?:private|protected)\b/.test(cleaned)) return null;
  const staticMember = implicitPublic || /\bstatic\b/.test(cleaned);
  if (!staticMember && !allowInstance) return null;
  const finalMember = /\bfinal\b/.test(cleaned);
  cleaned = cleaned.split("=")[0].trim();
  if (cleaned.includes("(")) return null;
  cleaned = cleaned
    .replace(/\b(?:public|protected|private|static|final|volatile|transient)\b/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const match = cleaned.match(/^(.*\S)\s+([A-Za-z_$][\w$]*)(\[\])?$/);
  if (!match) return null;
  return {
    kind: "field",
    name: match[2],
    static: staticMember,
    final: finalMember,
    type: cleanJavaType(`${match[1]}${match[3] || ""}`),
  };
}

function sourceTypeInfo(source, fqcn) {
  const simpleName = fqcn.slice(Math.max(fqcn.lastIndexOf("."), fqcn.lastIndexOf("$")) + 1);
  const cleaned = stripJavaComments(source);
  const visibility = fqcn.includes("$") ? "(?:public\\s+)?" : "public\\s+";
  const declaration = cleaned.match(new RegExp(
    `${visibility}((?:abstract\\s+|final\\s+|static\\s+)*)` +
    `(class|interface|enum|@interface)\\s+${simpleName}\\b([\\s\\S]*?)\\{`,
  ));
  if (!declaration) return { members: [], parents: [], typeParameters: [], kind: null, abstract: true };
  const modifiers = declaration[1];
  const kind = declaration[2];
  const implicitPublic = kind === "interface" || kind === "@interface";
  const declarationGenerics = leadingTypeParameters(declaration[3]);
  const tail = declaration[3].replace(/<[^<>]*(?:<[^<>]*>[^<>]*)*>/g, " ");
  const parents = [];
  for (const match of tail.matchAll(/\b(?:extends|implements)\s+([^\{]+?)(?=\b(?:extends|implements)\b|$)/g)) {
    for (const candidate of splitTopLevel(match[1])) {
      const parent = candidate.replace(/<.*>/, "").trim().split(".").at(-1);
      if (parent) parents.push(parent);
    }
  }

  const opening = declaration.index + declaration[0].length - 1;
  let depth = 1;
  let header = "";
  let enumPreamble = kind === "enum";
  const members = [];
  for (let index = opening + 1; index < cleaned.length && depth > 0; index++) {
    const character = cleaned[index];
    if (character === "{") {
      if (depth === 1 && !enumPreamble) {
        const field = fieldFromHeader(header, { implicitPublic, allowInstance: true });
        const executable = field ? null : executableFromHeader(header, simpleName, { implicitPublic });
        if (field) members.push(field);
        else if (executable) members.push(executable);
        header = "";
      }
      depth++;
      continue;
    }
    if (character === "}") {
      depth--;
      if (depth === 1) header = "";
      continue;
    }
    if (depth !== 1) continue;
    if (character === ";") {
      if (enumPreamble) {
        enumPreamble = false;
      } else {
        const field = fieldFromHeader(header, { implicitPublic, allowInstance: true });
        const executable = field ? null : executableFromHeader(header, simpleName, { implicitPublic });
        if (field) members.push(field);
        else if (executable) members.push(executable);
      }
      header = "";
      continue;
    }
    if (!enumPreamble) header += character;
  }
  return {
    members: members.map(member => ({
      ...member,
      ownerFqcn: fqcn,
      declaringTypeParameters: declarationGenerics.parameters,
    })),
    parents,
    typeParameters: declarationGenerics.parameters,
    kind,
    abstract: kind !== "class" || /\babstract\b/.test(modifiers),
  };
}

function inheritedSourceMembers(fqcn, types, sourceByClass, cache = new Map(), visiting = new Set()) {
  if (cache.has(fqcn)) return cache.get(fqcn);
  if (visiting.has(fqcn)) return [];
  visiting.add(fqcn);
  const detail = sourceByClass.get(fqcn);
  if (!detail) return [];
  const info = sourceTypeInfo(detail.text, fqcn);
  const inherited = info.parents.flatMap(parent => {
    const parentFqcn = types.get(parent);
    return parentFqcn
      ? inheritedSourceMembers(parentFqcn, types, sourceByClass, cache, visiting)
        .filter(member => member.kind !== "constructor")
      : [];
  });
  const unique = new Map();
  for (const member of [...inherited, ...info.members]) {
    const key = `${member.kind}:${member.static}:${member.name}:${member.parameters?.map(parameter => parameter.type).join(",") || ""}`;
    unique.set(key, member);
  }
  const result = [...unique.values()];
  cache.set(fqcn, result);
  visiting.delete(fqcn);
  return result;
}

function genericType(value) {
  const cleaned = cleanJavaType(value);
  const opening = cleaned.indexOf("<");
  if (opening < 0 || !cleaned.endsWith(">")) return { raw: cleaned, arguments: [] };
  return {
    raw: cleaned.slice(0, opening).trim(),
    arguments: splitTopLevel(cleaned.slice(opening + 1, -1)),
  };
}

function simpleTypeName(value) {
  return value.replaceAll("$", ".").split(".").at(-1);
}

function availableTypeReferences(types, ownerFqcn = null) {
  const references = new Map();
  const simpleCandidates = new Map();
  for (const [exportedName, fqcn] of types) {
    if (!references.has(exportedName)) references.set(exportedName, exportedName);
    if (!references.has(fqcn)) references.set(fqcn, exportedName);
    const dottedFqcn = fqcn.replaceAll("$", ".");
    if (!references.has(dottedFqcn)) references.set(dottedFqcn, exportedName);
    const binarySimpleName = fqcn.slice(fqcn.lastIndexOf(".") + 1);
    if (!references.has(binarySimpleName)) references.set(binarySimpleName, exportedName);
    const dottedSimpleName = binarySimpleName.replaceAll("$", ".");
    if (!references.has(dottedSimpleName)) references.set(dottedSimpleName, exportedName);
    const simpleName = simpleTypeName(fqcn);
    const candidates = simpleCandidates.get(simpleName) || new Set();
    candidates.add(fqcn);
    simpleCandidates.set(simpleName, candidates);
  }
  for (const [simpleName, candidates] of simpleCandidates) {
    if (candidates.size !== 1 || references.has(simpleName)) continue;
    const fqcn = [...candidates][0];
    references.set(simpleName, references.get(fqcn));
  }
  if (ownerFqcn) {
    const topLevelOwner = ownerFqcn.split("$")[0];
    for (const [exportedName, fqcn] of types) {
      if (!fqcn.startsWith(`${topLevelOwner}$`)) continue;
      references.set(simpleTypeName(fqcn), exportedName);
    }
  }
  if (!references.has("Result") && references.has("EventResult")) {
    references.set("Result", references.get("EventResult"));
  }
  return references;
}

function resolvedAvailableType(availableTypes, ...candidates) {
  for (const candidate of candidates) {
    if (!candidate) continue;
    if (availableTypes instanceof Map) {
      const resolved = availableTypes.get(candidate);
      if (resolved) return resolved;
    } else if (availableTypes.has(candidate)) {
      return candidate;
    }
  }
  return null;
}

const unresolvedTypes = {
  bukkit: { typeScript: new Set(), python: new Set() },
  packetEvents: { typeScript: new Set(), python: new Set() },
};
let unresolvedTypeDomain = "bukkit";

function recordUnresolvedType(language, type) {
  unresolvedTypes[unresolvedTypeDomain][language].add(type);
  if (process.env.DEBUG_POLYGLOT_TYPES === "1") {
    console.error(new Error(`Unresolved ${unresolvedTypeDomain}/${language}: ${type}`).stack);
  }
}

function standardJavaType(rawType) {
  const raw = genericType(rawType).raw;
  return /^(?:java|javax|jdk|sun)\./.test(raw);
}

function typeScriptType(javaType, availableTypes) {
  let cleaned = cleanJavaType(javaType);
  if (!cleaned) {
    recordUnresolvedType("typeScript", "<empty>");
    return "unknown";
  }
  if (cleaned.endsWith("[]")) return `${typeScriptType(cleaned.slice(0, -2), availableTypes)}[]`;
  const { raw, arguments: genericArguments } = genericType(cleaned);
  const simple = simpleTypeName(raw);
  if (["byte", "short", "int", "long", "float", "double", "Byte", "Short", "Integer", "Long", "Float", "Double", "Number"].includes(simple)) return "number";
  if (["boolean", "Boolean"].includes(simple)) return "boolean";
  if (["char", "Character", "String", "CharSequence"].includes(simple)) return "string";
  if (simple === "void" || simple === "Void") return "void";
  if (simple === "Object") return "unknown";
  if (simple === "Class") return `ApiClass<${typeScriptType(genericArguments[0] || "Object", availableTypes)}>`;
  if (simple === "Runnable") return "() => void";
  if (simple === "Callable") return `() => ${typeScriptType(genericArguments[0] || "Object", availableTypes)}`;
  if (["Supplier"].includes(simple)) return `() => ${typeScriptType(genericArguments[0] || "Object", availableTypes)}`;
  if (["Consumer", "Predicate"].includes(simple)) {
    const result = simple === "Predicate" ? "boolean" : "void";
    return `(value: ${typeScriptType(genericArguments[0] || "Object", availableTypes)}) => ${result}`;
  }
  if (simple === "Function") {
    return `(value: ${typeScriptType(genericArguments[0] || "Object", availableTypes)}) => ${typeScriptType(genericArguments[1] || "Object", availableTypes)}`;
  }
  if (["BiFunction", "BiConsumer", "BiPredicate"].includes(simple)) {
    const result = simple === "BiConsumer" ? "void"
      : simple === "BiPredicate" ? "boolean"
        : typeScriptType(genericArguments[2] || "Object", availableTypes);
    return `(left: ${typeScriptType(genericArguments[0] || "Object", availableTypes)}, right: ${typeScriptType(genericArguments[1] || "Object", availableTypes)}) => ${result}`;
  }
  if (["IntFunction", "LongFunction", "DoubleFunction"].includes(simple)) {
    return `(value: number) => ${typeScriptType(genericArguments[0] || "Object", availableTypes)}`;
  }
  if (simple === "Future") return `NativeFuture<${typeScriptType(genericArguments[0] || "Object", availableTypes)}>`;
  if (simple === "Random") return "NativeRandom";
  if (simple === "UUID") return "NativeUuid";
  if (simple === "Date") return "NativeDate";
  if (simple === "File") return "NativePath";
  if (simple === "Logger") return "NativeLogger";
  if (simple === "Thread") return "NativeThread";
  if (simple === "Optional") return `${typeScriptType(genericArguments[0] || "Object", availableTypes)} | null`;
  if (["Set", "HashSet", "EnumSet"].includes(simple)) {
    return `Set<${typeScriptType(genericArguments[0] || "Object", availableTypes)}>`;
  }
  if (["Collection", "List", "Iterable", "Iterator", "ArrayList", "ListIterator"].includes(simple)) {
    return `${typeScriptType(genericArguments[0] || "Object", availableTypes)}[]`;
  }
  if (["Map", "HashMap", "ConcurrentMap"].includes(simple)) {
    return `Map<${typeScriptType(genericArguments[0] || "Object", availableTypes)}, ${typeScriptType(genericArguments[1] || "Object", availableTypes)}>`;
  }
  if (knownTypeScriptTypes.has(simple)) return `Core.${knownTypeScriptTypes.get(simple)}`;
  const resolved = resolvedAvailableType(
    availableTypes,
    cleaned,
    raw,
    raw.replaceAll("$", "."),
    simple,
  );
  if (resolved) {
    if (!genericArguments.length) return resolved;
    const bounds = declaredGenericBounds.get(resolved) || [];
    const argumentsToRender = genericArguments.map((argument, index) => {
      const wildcard = cleanJavaType(argument) === "java.lang.Object" && argument.includes("?");
      const bound = bounds[index];
      const selected = wildcard && unresolvedTypeDomain === "bukkit" && bound ? bound
        : wildcard ? "Object" : argument;
      return typeScriptType(selected, availableTypes);
    });
    return `${resolved}<${argumentsToRender.join(", ")}>`;
  }
  if ([
    "AtomicInteger", "BaseComponent", "BufferedImage", "ClassLoader", "DumperOptions", "EbeanServer",
    "Image", "InetAddress", "InetSocketAddress", "InputStream", "LoaderOptions", "LogRecord", "Method",
    "MethodHandle", "OutputStream", "Reader", "ServerConfig", "Throwable", "Writer",
  ].includes(simple)) return "ApiObject";
  if (standardJavaType(raw)) return "ApiObject";
  recordUnresolvedType("typeScript", cleaned);
  return "unknown";
}

