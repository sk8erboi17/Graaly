  if (["byte", "short", "int", "long", "Byte", "Short", "Integer", "Long"].includes(simple)) return "int";
  if (["float", "double", "Float", "Double", "Number"].includes(simple)) return "float";
  if (["boolean", "Boolean"].includes(simple)) return "bool";
  if (["char", "Character", "String", "CharSequence"].includes(simple)) return "str";
  if (simple === "void" || simple === "Void") return "None";
  if (simple === "Object") return "Any";
  if (simple === "Class") return `type[${pythonType(genericArguments[0] || "Object", availableTypes)}]`;
  if (simple === "Runnable") return "Callable[[], None]";
  if (simple === "Callable") return `Callable[[], ${pythonType(genericArguments[0] || "Object", availableTypes)}]`;
