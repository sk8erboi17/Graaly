function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

function writeGenerated(path, contents) {
  mkdirSync(dirname(path), { recursive: true });
  const normalized = contents.endsWith("\n") ? contents : `${contents}\n`;
  if (!existsSync(path) || readFileSync(path, "utf8") !== normalized) {
    writeFileSync(path, normalized, "utf8");
  }
}

function properties(entries, heading) {
  const lines = [
    `# ${heading}`,
    "# Generated by scripts/generate-polyglot-catalogs.mjs; do not edit by hand.",
  ];
  for (const [name, fqcn] of [...entries].sort(([left], [right]) => left.localeCompare(right))) {
    lines.push(`${name}=${fqcn}`);
  }
  return lines.join("\n");
}

