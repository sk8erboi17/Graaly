function generatePythonApi(types, details) {
  const canonicalNameByFqcn = new Map();
  for (const [name, fqcn] of types) {
    const current = canonicalNameByFqcn.get(fqcn);
    if (!current || name === simpleTypeName(fqcn)) canonicalNameByFqcn.set(fqcn, name);
  }
  const names = [];
  const visited = new Set();
  const visiting = new Set();
  const visit = name => {
    if (visited.has(name) || visiting.has(name)) return;
    visiting.add(name);
    const fqcn = types.get(name);
    for (const parent of details.get(fqcn)?.parents || []) {
      const parentName = canonicalNameByFqcn.get(genericType(parent).raw);
      if (parentName) visit(parentName);
    }
    visiting.delete(name);
    visited.add(name);
    names.push(name);
  };
  for (const name of [...types.keys()].sort()) visit(name);

  const lines = [
    "# Generated Graaly 26.2 canonical API. Do not edit by hand.",
    "# pyright: reportOverlappingOverload=false, reportRedeclaration=false",
    "from collections.abc import Callable",
    "from typing import Any, ClassVar, Protocol, overload",
    "from .._base import ApiObject, NativeDate, NativeFuture, NativeLogger, NativePath, NativeRandom, NativeThread, NativeUuid",
    "",
  ];
  const memberCache = new Map();
  for (const name of names) {
    const fqcn = types.get(name);
    generatePythonPacketType(lines, name, fqcn, details.get(fqcn), types, details, memberCache, false);
  }
  return lines.join("\n");
}

function packetWrappers() {
  if (!existsSync(packetEventsJar)) {
    throw new Error(`PacketEvents API ${packetEventsVersion} is missing: ${packetEventsJar}`);
  }
  const classes = execFileSync("jar", ["tf", packetEventsJar], { encoding: "utf8" }).split(/\r?\n/);
  const result = new Map();
  for (const entry of classes) {
    if (!entry.startsWith("com/github/retrooper/packetevents/wrapper/") || !entry.endsWith(".class") || entry.includes("$")) continue;
    const fqcn = entry.replaceAll("/", ".").replace(/\.class$/, "");
    const simpleName = fqcn.slice(fqcn.lastIndexOf(".") + 1);
    if (!simpleName.startsWith("Wrapper") || simpleName === "PacketWrapper") continue;
    if (result.has(simpleName) && result.get(simpleName) !== fqcn) {
      throw new Error(`Duplicate PacketEvents wrapper ${simpleName}`);
    }
    result.set(simpleName, fqcn);
  }
  return result;
}

function packetTypes() {
  const states = ["Handshaking", "Status", "Login", "Configuration", "Play"];
  const directions = ["Client", "Server"];
  const result = [];
  for (const state of states) {
    for (const direction of directions) {
      const className = `com.github.retrooper.packetevents.protocol.packettype.PacketType$${state}$${direction}`;
      const output = execFileSync("javap", ["-classpath", packetEventsJar, "-public", className], { encoding: "utf8" });
      const fieldPattern = /public static final\s+\S+\s+([A-Z][A-Z0-9_]*)\s*;/g;
      for (const match of output.matchAll(fieldPattern)) {
        result.push(`${state}.${direction}.${match[1]}`);
      }
    }
  }
  return [...new Set(result)].sort();
}

function javapEnumConstants(detail, fqcn) {
  if (detail?.kind !== "enum") return [];
  return detail.members
    .filter(member => member.kind === "field" && member.static
      && member.final && cleanJavaType(member.type) === fqcn
      && /^[A-Z][A-Z0-9_]*$/.test(member.name))
    .map(member => member.name);
}

function documentationEventsJavap(types, details) {
  const memberCache = new Map();
  return [...types]
    .flatMap(([name, javaName]) => {
      const detail = details.get(javaName);
      if (!detail || detail.abstract || !javaName.includes(".event.") || !name.endsWith("Event")) return [];
      const members = inheritedJavapMembers(javaName, details, memberCache);
      if (!members.some(member => member.kind === "method" && member.name === "getHandlers")) return [];
      const eventPackage = javaName.slice(0, javaName.lastIndexOf(".")).split(".event.")[1] || "general";
      const category = eventPackage.split(".")[0];
      const eventProperties = memberProperties(members)
        .filter(property => !["handlers", "eventName", "asynchronous"].includes(property.name))
        .map(property => ({
          name: property.name,
          pythonName: safePythonMemberName(property.name),
          javaType: cleanJavaType(property.type),
          typeScriptType: typeScriptType(
            property.type,
            availableTypeReferences(types, property.ownerFqcn || javaName),
          ),
          pythonType: pythonType(
            property.type,
            availableTypeReferences(types, property.ownerFqcn || javaName),
          ),
          javaRead: property.getter ? `${property.getter.name}()` : property.name,
          javaWrite: property.setter ? `${property.setter.name}(value)` : null,
          writable: property.writable,
        }));
      return [{
        name,
        javaName,
        category: category || "general",
        cancellable: eventProperties.some(property => property.name === "cancelled"),
        properties: eventProperties,
      }];
    })
    .sort((left, right) => left.name.localeCompare(right.name));
}

function documentationMembers(exportedName, fqcn, detail, types, { enumConstants: constants = [], wrapper = false } = {}) {
  if (!detail) return [];
  const references = availableTypeReferences(types, fqcn);
  const members = detail.members || [];
  const enumType = detail.kind === "enum" || constants.length > 0;
  const properties = memberProperties(members, enumType);
  const propertyNames = new Set(properties.map(property => property.name));
  const rows = [];
  const javaScriptParameters = member => member.parameters.map((parameter, index) =>
    `${parameter.varArgs ? "..." : ""}${safeParameterName(parameter.name, index)}`,
  ).join(", ");
  const javaParameters = member => member.parameters.map((parameter, index) =>
    `${cleanJavaType(parameter.type)}${parameter.varArgs ? "..." : ""} ${safeParameterName(parameter.name, index)}`,
  ).join(", ");
  for (const constant of constants) {
    rows.push({ kind: "constant", name: constant, java: `${exportedName}.${constant}`, javaScript: constant, typeScript: `${constant}: ${exportedName}`, python: `${constant}: ${exportedName}` });
  }
  if (constants.length) {
    rows.push({
      kind: "static method",
      name: "values",
      java: `${exportedName}.values(): ${exportedName}[]`,
      javaScript: "values()",
      typeScript: `values(): ${exportedName}[]`,
      python: `values() -> list[${exportedName}]`,
    });
    rows.push({
      kind: "static method",
      name: "valueOf",
      java: `${exportedName}.valueOf(String name): ${exportedName}`,
      javaScript: "valueOf(name)",
      typeScript: `valueOf(name: string): ${exportedName}`,
      python: `value_of(name: str) -> ${exportedName}`,
    });
  }
  for (const member of members.filter(member => member.kind === "field")) {
    if (constants.includes(member.name)) continue;
    const prefix = member.static ? "static " : member.final ? "readonly " : "";
    const typeScriptContext = typeReferencesWithParameters(references, member, "typeScript");
    const pythonContext = typeReferencesWithParameters(references, member, "python");
    rows.push({
      kind: member.static ? "static field" : "field",
      name: member.name,
      java: `${member.static ? `${exportedName}.` : ""}${member.name}: ${cleanJavaType(member.type)}`,
      javaScript: member.name,
      typeScript: `${prefix}${member.name}: ${typeScriptType(member.type, typeScriptContext)}`,
      python: `${safePythonMemberName(member.name)}: ${pythonType(member.type, pythonContext)}`,
    });
  }
  for (const property of properties) {
    const typeScriptContext = typeReferencesWithParameters(references, property, "typeScript");
    const pythonContext = typeReferencesWithParameters(references, property, "python");
    rows.push({
      kind: "property",
      name: property.name,
      java: [
        property.getter ? `${property.getter.name}(): ${cleanJavaType(property.type)}` : `${property.name}: ${cleanJavaType(property.type)}`,
        property.setter ? `${property.setter.name}(${cleanJavaType(property.type)} value): void` : null,
      ].filter(Boolean).join(" / "),
      javaScript: property.name,
      typeScript: `${property.writable ? "" : "readonly "}${property.name}: ${typeScriptType(property.type, typeScriptContext)}`,
      python: `${safePythonMemberName(property.name)}: ${pythonType(property.type, pythonContext)}`,
    });
  }
  for (const constructor of members.filter(member => member.kind === "constructor"
    && (!wrapper || usableWrapperConstructor(member)))) {
    const constructorContext = typeReferencesWithParameters(references, constructor, "typeScript");
    const pythonContext = typeReferencesWithParameters(references, constructor, "python");
    const typeScriptGenerics = typeScriptTypeParameters([
      ...(detail.typeParameters || []),
      ...(constructor.typeParameters || []),
    ], constructorContext);
    const pythonGenerics = pythonTypeParameters(constructor.typeParameters, pythonContext);
    rows.push({
      kind: "constructor",
      name: exportedName,
      java: `new ${exportedName}(${javaParameters(constructor)})`,
      javaScript: `${exportedName}(${javaScriptParameters(constructor)})`,
      typeScript: `${exportedName}${typeScriptGenerics}(${typeScriptParameters(constructor, constructorContext)})`,
      python: `${exportedName}${pythonGenerics}(${pythonParameters(constructor, pythonContext)})`,
    });
  }
  const methodRows = members.filter(member => member.kind === "method"
    && !(enumType && (member.name === "name" || member.name === "ordinal")));
  for (const method of methodRows) {
    const typeScriptContext = typeReferencesWithParameters(references, method, "typeScript");
    const pythonContext = typeReferencesWithParameters(references, method, "python");
    const typeScriptGenerics = typeScriptTypeParameters(method.typeParameters, typeScriptContext);
    const pythonGenerics = pythonTypeParameters(method.typeParameters, pythonContext);
    rows.push({
      kind: method.static ? "static method" : "method",
      name: method.name,
      java: `${method.static ? `${exportedName}.` : ""}${method.name}(${javaParameters(method)}): ${cleanJavaType(method.type)}`,
      javaScript: `${method.name}(${javaScriptParameters(method)})`,
      typeScript: `${method.static ? "static " : ""}${method.name}${typeScriptGenerics}(${typeScriptParameters(method, typeScriptContext)}): ${typeScriptType(method.type, typeScriptContext)}`,
      python: `${safePythonMemberName(method.name)}${pythonGenerics}(${pythonParameters(method, pythonContext)}) -> ${pythonType(method.type, pythonContext)}`,
    });
  }
  return rows;
}

function documentationParentNames(fqcn, detail, types) {
  if (!detail) return [];
  const references = availableTypeReferences(types, fqcn);
  return [...new Set((detail.parents || []).flatMap(parent => {
    const parsed = genericType(parent);
    const resolved = resolvedAvailableType(
      references,
      parent,
      parsed.raw,
      parsed.raw.replaceAll("$", "."),
      simpleTypeName(parsed.raw),
    );
    return resolved ? [resolved] : [];
  }))];
}

