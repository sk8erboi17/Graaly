  if (!cleaned) {
    recordUnresolvedType("python", "<empty>");
    return "Any";
  }
  if (cleaned.endsWith("[]")) return `list[${pythonType(cleaned.slice(0, -2), availableTypes)}]`;
  const { raw, arguments: genericArguments } = genericType(cleaned);
